"""WhatsApp phone OTP tests — backend-generated 6-digit codes verified via endpoint.

Phone verification codes are generated by the backend, delivered over
WhatsApp, and verified with POST /auth/security/otp/verify
{session_id, channel: "phone", code}. Booking stays blocked until verified.
"""
import uuid
from datetime import datetime, timedelta, timezone

import pytest
from httpx import AsyncClient
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.models.organization import Organization
from app.models.config import OrgConfig
from app.models.session import ChatSession
from app.models.booking import Booking, TimeSlot


BOOKING_DATE = (datetime.now(timezone.utc) + timedelta(days=30)).date().isoformat()


async def _make_org_with_phone_otp(db: AsyncSession, *, require_phone_otp: bool = True, require_otp: bool = False) -> Organization:
    org = Organization(name="WhatsApp OTP Org", api_key=f"ds_wa_{uuid.uuid4().hex[:12]}", is_active=True)
    db.add(org)
    await db.flush()
    cfg = OrgConfig(org_id=org.id, required_fields=["name", "email", "phone", "date", "time"])
    cfg.require_otp = require_otp
    cfg.require_phone_otp = require_phone_otp
    db.add(cfg)
    await db.commit()
    await db.refresh(org)
    return org


async def _make_session(db: AsyncSession, org: Organization, phone: str = "+916350063338") -> ChatSession:
    sess = ChatSession(
        org_id=org.id,
        state_data={
            "phone": phone,
            "name": "Test User",
            "email": "test@example.com",
            "date": BOOKING_DATE,
            "time": "10:00",
            "user_timezone": "UTC",
        },
        missing_fields=[],
        current_intent="CONFIRM_BOOKING",
        session_status="ACTIVE",
        otp_verified=True,  # email done, phone pending
        phone_otp_verified=False,
    )
    db.add(sess)
    await db.commit()
    await db.refresh(sess)
    return sess


async def _refresh_session(db: AsyncSession, sid: str) -> ChatSession:
    db.expire_all()
    refreshed = await db.execute(select(ChatSession).where(ChatSession.id == uuid.UUID(sid)))
    session = refreshed.scalars().first()
    assert session is not None
    return session


class TestWhatsAppVerifyEndpoint:
    async def test_valid_code_succeeds(self, client: AsyncClient, db_session: AsyncSession):
        from app.crud.otp import generate_otp

        org = await _make_org_with_phone_otp(db_session)
        sess = await _make_session(db_session, org, phone="+916350063338")
        sid = str(sess.id)
        code = await generate_otp(db_session, sid, channel="phone")

        resp = await client.post(
            "/api/v1/auth/security/otp/verify",
            json={"session_id": sid, "channel": "phone", "code": code},
            headers={"X-Requested-With": "XMLHttpRequest"},
        )
        assert resp.status_code == 200, resp.text
        assert resp.json()["status"] == "success"
        assert (await _refresh_session(db_session, sid)).phone_otp_verified is True

    async def test_wrong_code_rejected_400(self, client: AsyncClient, db_session: AsyncSession):
        from app.crud.otp import generate_otp

        org = await _make_org_with_phone_otp(db_session)
        sess = await _make_session(db_session, org)
        sid = str(sess.id)
        await generate_otp(db_session, sid, channel="phone")

        resp = await client.post(
            "/api/v1/auth/security/otp/verify",
            json={"session_id": sid, "channel": "phone", "code": "000000"},
            headers={"X-Requested-With": "XMLHttpRequest"},
        )
        assert resp.status_code == 400, resp.text
        assert "invalid" in resp.text.lower()
        assert (await _refresh_session(db_session, sid)).phone_otp_verified is False

    async def test_missing_code_rejected_400(self, client: AsyncClient, db_session: AsyncSession):
        org = await _make_org_with_phone_otp(db_session)
        sess = await _make_session(db_session, org)
